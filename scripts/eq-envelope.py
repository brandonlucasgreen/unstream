#!/usr/bin/env python3
"""Turn a song into the frames the homepage's equalizer band plays back.

    python3 scripts/eq-envelope.py <audio file> [--start SECONDS] [--seconds 24]

Writes apps/web/src/data/eq-song.ts. Only band levels are written, never audio:
the file holds FRAME_RATE frames a second of BAND_COUNT levels, one base-36
character per level (0 = silent, z = loudest). Without --start it picks the
liveliest stretch of the song (most change between frames, at a good volume),
skipping the first and last 20 seconds.

Needs ffmpeg on the PATH and numpy. Re-run it to change the song or the
stretch; update SONG_CREDIT in EqualizerBand.tsx to match.
"""

import argparse
import subprocess
import sys
from pathlib import Path

import numpy as np

SAMPLE_RATE = 22050
FRAME_RATE = 20
BAND_COUNT = 44  # keep equal to the bar count in EqualizerBand.tsx
FFT_SIZE = 2048
LOW_HZ, HIGH_HZ = 40, 11000
# Meter ballistics: bars jump up at once and fall back at this rate per frame,
# the way a hardware level meter does. Without it they flicker.
DECAY = 0.72
LOOP_BLEND_FRAMES = 10
LEVELS = 36
OUT = Path(__file__).resolve().parent.parent / "apps/web/src/data/eq-song.ts"


def read_mono(path: str) -> np.ndarray:
    raw = subprocess.run(
        ["ffmpeg", "-v", "error", "-i", path, "-ac", "1", "-ar", str(SAMPLE_RATE), "-f", "f32le", "-"],
        check=True, capture_output=True,
    ).stdout
    return np.frombuffer(raw, dtype=np.float32)


def band_energies(samples: np.ndarray) -> np.ndarray:
    """Per frame, the log energy in each of BAND_COUNT log-spaced bands."""
    hop = SAMPLE_RATE // FRAME_RATE
    window = np.hanning(FFT_SIZE)
    freqs = np.fft.rfftfreq(FFT_SIZE, 1 / SAMPLE_RATE)
    edges = np.geomspace(LOW_HZ, HIGH_HZ, BAND_COUNT + 1)
    # Each band takes at least one FFT bin, so the narrow bass bands aren't empty.
    bins = [np.flatnonzero((freqs >= lo) & (freqs < hi)) for lo, hi in zip(edges[:-1], edges[1:])]
    bins = [b if len(b) else np.array([np.argmin(np.abs(freqs - lo))]) for b, lo in zip(bins, edges[:-1])]

    count = (len(samples) - FFT_SIZE) // hop
    out = np.empty((count, BAND_COUNT))
    for f in range(count):
        spectrum = np.abs(np.fft.rfft(samples[f * hop : f * hop + FFT_SIZE] * window)) ** 2
        out[f] = [10 * np.log10(spectrum[b].mean() + 1e-12) for b in bins]
    return out


def liveliest_start(energy: np.ndarray, length: int) -> int:
    loudness = energy.mean(axis=1)
    flux = np.concatenate([[0], np.abs(np.diff(energy, axis=0)).mean(axis=1)])
    score = flux * np.clip(loudness - np.percentile(loudness, 20), 0, None)
    margin = 20 * FRAME_RATE
    candidates = range(margin, len(energy) - length - margin, FRAME_RATE)
    if not candidates:
        return 0
    return max(candidates, key=lambda s: score[s : s + length].mean())


def to_levels(energy: np.ndarray) -> np.ndarray:
    # Normalise each band against itself, so treble moves as visibly as bass,
    # then tilt gently so the low end still stands tallest, as it does in music.
    lo = np.percentile(energy, 15, axis=0)
    hi = np.percentile(energy, 99, axis=0)
    levels = np.clip((energy - lo) / np.maximum(hi - lo, 1e-6), 0, 1)
    levels *= np.linspace(1.0, 0.8, BAND_COUNT)

    for f in range(1, len(levels)):
        levels[f] = np.maximum(levels[f], levels[f - 1] * DECAY)

    # Fade the last frames into the first so the loop has no visible jump.
    for i in range(LOOP_BLEND_FRAMES):
        t = (i + 1) / (LOOP_BLEND_FRAMES + 1)
        f = len(levels) - LOOP_BLEND_FRAMES + i
        levels[f] = levels[f] * (1 - t) + levels[0] * t
    return levels


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("audio")
    parser.add_argument("--start", type=float, help="seconds into the song; default: the liveliest stretch")
    parser.add_argument("--seconds", type=float, default=24)
    args = parser.parse_args()

    energy = band_energies(read_mono(args.audio))
    length = int(args.seconds * FRAME_RATE)
    start = int(args.start * FRAME_RATE) if args.start is not None else liveliest_start(energy, length)
    if start + length > len(energy):
        sys.exit("The stretch runs past the end of the song.")

    # Normalise against the whole song, then cut the stretch, so a quiet
    # passage reads as quiet rather than being stretched to full height.
    levels = to_levels(energy)[start : start + length]
    digits = np.round(levels * (LEVELS - 1)).astype(int)
    frames = "".join(np.base_repr(d, 36).lower() for d in digits.flatten())

    OUT.write_text(
        "// Generated by scripts/eq-envelope.py; re-run it rather than editing.\n"
        f"// {Path(args.audio).name}, {start / FRAME_RATE:.1f}s to {(start + length) / FRAME_RATE:.1f}s.\n"
        f"export const EQ_FRAME_RATE = {FRAME_RATE};\n"
        f"export const EQ_BAND_COUNT = {BAND_COUNT};\n"
        f"export const EQ_FRAMES = '{frames}';\n"
    )
    print(f"Wrote {OUT.relative_to(Path.cwd()) if OUT.is_relative_to(Path.cwd()) else OUT}: "
          f"{length} frames from {start / FRAME_RATE:.1f}s, {len(frames)} characters")


if __name__ == "__main__":
    main()
